-- Schéma collaboration + enregistrement migration (équivalent à doctrine:migrations:migrate)
-- Usage : se connecter à la base collaboration_db (utilisateur collab ou postgres), puis exécuter ce script.
-- Ex. pgAdmin : requête sur la base collaboration_db.

CREATE TABLE IF NOT EXISTS collaboration (
    id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id VARCHAR(128) NOT NULL,
    user_name VARCHAR(255) NOT NULL DEFAULT '',
    type VARCHAR(16) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    published_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    priority VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

ALTER TABLE collaboration ADD COLUMN IF NOT EXISTS user_name VARCHAR(255) NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS doctrine_migration_versions (
    version VARCHAR(191) NOT NULL,
    executed_at TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT NULL,
    execution_time INT DEFAULT NULL,
    PRIMARY KEY (version)
);

